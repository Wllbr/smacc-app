#!/usr/bin/env python3
"""Builds app/src/main/assets/zod_bundle.js from the Chrome extension in extension/.

The app runs this one script at document start on every https://*.smacc.com page (all frames).
It follows manifest.json's content_scripts the way Chrome does:
  main.js   document_start, all frames, page world
  fast.js   document_start, top frame (+ style.css)
  cust.js   document_idle,  top frame
  zod.js    document_idle,  top frame, invoice / return pages
  tools.js  document_idle,  top frame, item card / invoice pages, page world
Scripts written for Chrome's isolated world get a stand-in `chrome` object (android-js/chrome-shim.js).

To update the app with a new version of the extension: replace extension/ and push; the GitHub
build runs this script again.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXT = ROOT / "extension"
AJS = ROOT / "android-js"
OUT = ROOT / "app" / "src" / "main" / "assets" / "zod_bundle.js"


def read(p):
    return p.read_text(encoding="utf-8")


manifest = json.loads(read(EXT / "manifest.json"))
mini = {k: manifest.get(k) for k in ("name", "short_name", "version", "description")}
shim = read(AJS / "chrome-shim.js").replace("__MANIFEST__", json.dumps(mini, ensure_ascii=False))
css = read(EXT / "style.css") + "\n" + read(AJS / "android.css")


def page_world(name):
    return "run(%s, function () {\n%s\n});\n" % (json.dumps(name), read(EXT / name))


def isolated(name):
    return "run(%s, function () { (function (chrome) {\n%s\n}).call(window, ZCHROME); });\n" % (
        json.dumps(name), read(EXT / name))


bundle = """/* Generated by tools/build_bundle.py from extension/ (v%(ver)s). Do not edit by hand. */
(function () {
if (window.__zodAndroid || /^\\/zod-app\\//.test(location.pathname)) return;
window.__zodAndroid = true;
var TOP = window.top === window;
var PATH = location.pathname;
function run(name, fn) { try { fn(); } catch (e) { console.error('[zod] ' + name, e); } }
function idle(fn) {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { fn(); }, { once: true });
  else fn();
}
var ZCHROME = (%(shim)s)();
%(android)s
/* ---- main.js (all frames) ---- */
%(main)s
if (TOP) {
  addCss(%(css)s);
  /* ---- fast.js ---- */
  %(fast)s
  idle(function () {
    /* ---- cust.js ---- */
    %(cust)s
    if (/^\\/Inventory\\/(PurchaseInvoicePage|PurchaseReturnPage|SalesInvoicePage|SalesReturnPage)\\.aspx/.test(PATH) || /^\\/inventory\\//.test(PATH)) {
      /* ---- zod.js ---- */
      %(zod)s
    }
    if (/^\\/Inventory\\/(ItemCardMasterPage|SalesInvoicePage|PurchaseInvoicePage)\\.aspx/.test(PATH) || /^\\/inventory\\//.test(PATH)) {
      /* ---- tools.js ---- */
      %(tools)s
    }
  });
}
})();
""" % {
    "ver": manifest.get("version", "?"),
    "shim": shim,
    "android": read(AJS / "android.js"),
    "main": page_world("main.js"),
    "css": json.dumps(css, ensure_ascii=False),
    "fast": isolated("fast.js"),
    "cust": isolated("cust.js"),
    "zod": isolated("zod.js"),
    "tools": page_world("tools.js"),
}

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(bundle, encoding="utf-8")
print("wrote %s (%d KB, extension v%s)" % (OUT.relative_to(ROOT), len(bundle.encode()) // 1024, manifest.get("version")))
